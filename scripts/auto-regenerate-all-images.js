const { PrismaClient } = require("@prisma/client");
const prisma = new PrismaClient();

// We'll use fetch to call the APIs instead of importing TS modules
const fetch = (...args) => import('node-fetch').then(({default: fetch}) => fetch(...args));

/**
 * Script automático para re-gerar TODAS as imagens de artigos usando IA
 * 
 * Este script:
 * 1. Identifica artigos com imagens quebradas
 * 2. Gera novas imagens usando Gemini/DALL-E
 * 3. Faz upload para InterServer
 * 4. Atualiza o banco de dados
 */

async function generateImageForArticle(article) {
  try {
    console.log(`\n🎨 Gerando imagem para: "${article.title}"`);
    
    // Create prompt based on article title
    const prompt = `Professional article cover image for physiotherapy clinic blog: ${article.title}. Medical, healthcare, modern, clean, professional photography style.`;
    
    console.log(`   Prompt: ${prompt.substring(0, 100)}...`);
    console.log(`   Aguardando geração com IA (60-120s)...`);
    
    // Generate image using AI
    const imageUrls = await generateImageSmart(prompt, { numImages: 1 });
    
    if (!imageUrls || imageUrls.length === 0) {
      throw new Error('No image generated by AI');
    }

    const dataUrl = imageUrls[0];
    console.log(`   ✅ Imagem gerada com sucesso!`);

    let finalImageUrl = dataUrl;
    
    // Upload to InterServer if configured
    if (isInterServerConfigured() && dataUrl.startsWith('data:')) {
      try {
        console.log(`   📤 Fazendo upload para InterServer...`);
        
        const base64Data = dataUrl.split(',')[1];
        const buffer = Buffer.from(base64Data, 'base64');
        const filename = `article-${article.slug}-${Date.now()}.png`;
        
        finalImageUrl = await uploadToInterServer(buffer, filename);
        console.log(`   ✅ Upload concluído: ${finalImageUrl}`);
      } catch (uploadErr) {
        console.log(`   ⚠️  Upload falhou, usando data URL:`, uploadErr.message);
        finalImageUrl = dataUrl;
      }
    }

    // Update article in database
    await prisma.article.update({
      where: { id: article.id },
      data: { imageUrl: finalImageUrl },
    });

    console.log(`   💾 Banco de dados atualizado!`);
    
    return { success: true, imageUrl: finalImageUrl };
    
  } catch (error) {
    console.error(`   ❌ Erro ao gerar imagem:`, error.message);
    return { success: false, error: error.message };
  }
}

async function autoRegenerateAllImages() {
  console.log("🚀 AUTO-REGENERAÇÃO DE TODAS AS IMAGENS\n");
  console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

  try {
    // Find all articles with broken images
    const articles = await prisma.article.findMany({
      select: {
        id: true,
        title: true,
        slug: true,
        imageUrl: true,
        excerpt: true,
      },
      orderBy: {
        createdAt: 'desc',
      },
    });

    const brokenArticles = articles.filter(article => 
      article.imageUrl && 
      (article.imageUrl.startsWith('/uploads/') || article.imageUrl.startsWith('data:'))
    );

    console.log(`📊 Artigos encontrados: ${articles.length}`);
    console.log(`❌ Com imagens quebradas: ${brokenArticles.length}\n`);

    if (brokenArticles.length === 0) {
      console.log("✅ Nenhum artigo precisa de nova imagem!\n");
      return;
    }

    console.log(`🎯 Iniciando re-geração de ${brokenArticles.length} imagens...\n`);
    console.log("⏱️  Tempo estimado: ${brokenArticles.length * 90}s (~${Math.ceil(brokenArticles.length * 90 / 60)} minutos)\n");

    const results = {
      success: 0,
      failed: 0,
      errors: [],
    };

    // Process each article sequentially (to avoid overwhelming the API)
    for (let i = 0; i < brokenArticles.length; i++) {
      const article = brokenArticles[i];
      console.log(`\n[${i + 1}/${brokenArticles.length}] Processando...`);
      
      const result = await generateImageForArticle(article);
      
      if (result.success) {
        results.success++;
      } else {
        results.failed++;
        results.errors.push({
          article: article.title,
          error: result.error,
        });
      }

      // Wait 2 seconds between requests to avoid rate limiting
      if (i < brokenArticles.length - 1) {
        console.log(`\n   ⏸️  Aguardando 2s antes do próximo...`);
        await new Promise(resolve => setTimeout(resolve, 2000));
      }
    }

    console.log("\n\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    console.log("📊 RESULTADO FINAL:\n");
    console.log(`   ✅ Sucesso: ${results.success}/${brokenArticles.length}`);
    console.log(`   ❌ Falhas: ${results.failed}/${brokenArticles.length}`);

    if (results.errors.length > 0) {
      console.log("\n❌ ERROS:\n");
      results.errors.forEach((err, i) => {
        console.log(`   ${i + 1}. ${err.article}`);
        console.log(`      ${err.error}\n`);
      });
    }

    if (results.success > 0) {
      console.log("\n✅ IMAGENS RE-GERADAS COM SUCESSO!");
      console.log("🌐 Acesse https://bpr.rehab para verificar\n");
    }

  } catch (error) {
    console.error("\n❌ Erro fatal:", error);
  } finally {
    await prisma.$disconnect();
  }
}

// Run the script
autoRegenerateAllImages();
